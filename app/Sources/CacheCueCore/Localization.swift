    /// Claude Code's name for what caused a cache miss, in words; a name not known here is
    /// shown as it came.
    public func missCause(named name: String) -> String {
        switch name {
        case "tools_changed": return causeToolsChanged
        case "system_prompt_changed": return causeSystemPrompt
        case "ttl_expired_5m": return causeExpired
        case "likely_server_side": return causeServer
        default: return name.replacingOccurrences(of: "_", with: " ")
        }
    }

